-- 1. quickbooks_connections
--    One row per user with a connected QuickBooks Online company.
--    Tokens are encrypted at rest (same AES-256-GCM scheme as
--    square_connections.access_token_enc / refresh_token_enc).

CREATE TABLE IF NOT EXISTS quickbooks_connections (
  id                         SERIAL PRIMARY KEY,
  user_id                    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  realm_id                   TEXT NOT NULL,
    -- QuickBooks company id, returned on the OAuth callback
  access_token_enc           TEXT NOT NULL,
  refresh_token_enc          TEXT NOT NULL,
  access_token_expires_at    TIMESTAMPTZ NOT NULL,
  refresh_token_expires_at   TIMESTAMPTZ NOT NULL,
    -- QBO refresh tokens rotate and expire (~100 days); tracked separately
    -- from the short-lived access token so the sync job knows when a
    -- full reconnect is required vs. a simple refresh.
  environment                TEXT NOT NULL DEFAULT 'sandbox'
    CHECK (environment IN ('sandbox', 'production')),
  sync_status                TEXT,
  sync_completed_at          TIMESTAMPTZ,
  sync_error                 TEXT,
  connected_at               TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at                 TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (user_id)
);

-- 2. product_cost_mappings
--    Aervo product (aervo_products) <-> QuickBooks item, one row per
--    product per user. Rows are created for every product on sync,
--    even with no match, so the mapping UI has something to list.
--    match_type: 'auto' | 'manual' | 'unmatched'

CREATE TABLE IF NOT EXISTS product_cost_mappings (
  id                  SERIAL PRIMARY KEY,
  user_id             INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  aervo_product_id    INTEGER NOT NULL REFERENCES aervo_products(id) ON DELETE CASCADE,
  quickbooks_item_id  TEXT,
    -- nullable until matched
  match_type          VARCHAR(20) NOT NULL DEFAULT 'unmatched'
    CHECK (match_type IN ('auto', 'manual', 'unmatched')),
  created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (user_id, aervo_product_id)
);

-- 3. margin_snapshots
--    Cached per-product margin results for a period, regenerated by
--    the nightly sync. One row per user per period; period_start is
--    used to look up the prior period for digest comparisons.

CREATE TABLE IF NOT EXISTS margin_snapshots (
  id            SERIAL PRIMARY KEY,
  user_id       INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  period_type   VARCHAR(20) NOT NULL DEFAULT 'week',
    -- 'week' | 'month', room to extend later
  period_start  DATE NOT NULL,
  period_end    DATE NOT NULL,
  data          JSONB NOT NULL,
    -- array of { aervo_product_id, revenue, cost, margin_pct, estimated }
  generated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (user_id, period_type, period_start)
);

-- 4. digests
--    Cached weekly narrative digest text, generated once per period
--    and served from cache on subsequent requests (never regenerated
--    on page load — same pattern as Smart Playbooks).

CREATE TABLE IF NOT EXISTS digests (
  id            SERIAL PRIMARY KEY,
  user_id       INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  period_type   VARCHAR(20) NOT NULL DEFAULT 'week',
  period_start  DATE NOT NULL,
  period_end    DATE NOT NULL,
  headline      TEXT NOT NULL,
  body          TEXT NOT NULL,
  generated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (user_id, period_type, period_start)
);

-- ============================================================
-- Indexes
-- ============================================================

CREATE INDEX IF NOT EXISTS idx_quickbooks_connections_user_id
  ON quickbooks_connections(user_id);

CREATE INDEX IF NOT EXISTS idx_product_cost_mappings_user_id
  ON product_cost_mappings(user_id);

CREATE INDEX IF NOT EXISTS idx_product_cost_mappings_user_match_type
  ON product_cost_mappings(user_id, match_type);

CREATE INDEX IF NOT EXISTS idx_margin_snapshots_user_period
  ON margin_snapshots(user_id, period_type, period_start);

CREATE INDEX IF NOT EXISTS idx_digests_user_period
  ON digests(user_id, period_type, period_start);

-- ============================================================
-- Auto-update updated_at (reuses the trigger function created in
-- 001_square_integration.sql; safe to redefine here too)
-- ============================================================

CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS set_quickbooks_connections_updated_at ON quickbooks_connections;
CREATE TRIGGER set_quickbooks_connections_updated_at
  BEFORE UPDATE ON quickbooks_connections
  FOR EACH ROW
  EXECUTE FUNCTION update_updated_at_column();

DROP TRIGGER IF EXISTS set_product_cost_mappings_updated_at ON product_cost_mappings;
CREATE TRIGGER set_product_cost_mappings_updated_at
  BEFORE UPDATE ON product_cost_mappings
  FOR EACH ROW
  EXECUTE FUNCTION update_updated_at_column();

